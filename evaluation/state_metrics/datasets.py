@dataclass(frozen=True)
class DatasetSpec:
    name: str
    bpmn: Path
    params: Path
    remove_from_profile: str    # which resource_profiles[].name to shrink
    default_runs: int = 5
    default_levels: tuple[int, ...] = (0, 1, 2)
    # Ladder used when --perturbation duration is selected. Values are
    # integer percentages, mapped by the pipeline to scale = 1 + level/100.
    default_duration_levels: tuple[int, ...] = (0, 25, 50, 100, 200, 300)
    # parallel_auto: the non-critical AND-branch tasks to automate.
    automate_task_ids: tuple[str, ...] = ()
    # front_back_load: the ordered sequential-chain tasks to reweight.
    chain_task_ids: tuple[str, ...] = ()
    # front_back_swap: the two equal-total XOR branches whose profiles are
    # swapped (positional correspondence swap_p_task_ids[i] <-> swap_q_task_ids[i]).
    swap_p_task_ids: tuple[str, ...] = ()
    swap_q_task_ids: tuple[str, ...] = ()
    # front_back_swap: which branch positions the swap touches (1-based).
    # Empty = every position.
    swap_positions: tuple[int, ...] = ()
    # route_error_graded: which split gateways carry the routing error
    # (1-based, in gateway-id order). Empty = every split gateway.
    route_gateway_positions: tuple[int, ...] = ()
    # The perturbation EXTENT this model carries, and the size of the geometry
    # it is drawn from. Both families' models are built as a centred window of
    # `perturb_extent` of `geometry_size` elements, so a family's three models
    # are nested and every family picks its elements by the same rule.
    perturb_extent: int = 0
    geometry_size: int = 0


